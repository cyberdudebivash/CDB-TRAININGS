#!/usr/bin/env python3
"""Render the October 2026 research documents from the evidence data (deterministic; no timestamps).

Inputs : docs/research/{technology_registry.yaml,research_register.yaml,deprecation_rules.yaml,new_developments.yaml}
         docs/research/data/{registry_snapshot_<cutoff>.json,api_probes_<cutoff>.json}
         docs/audits/data/page_records (technology usage), catalog/courses.yaml
Outputs: docs/research/TECHNOLOGY_BASELINES_2026.md
         docs/research/RESEARCH_VERIFICATION_2026.md
         docs/research/NEW_DEVELOPMENTS_2026.md

Run:    .venv/bin/python scripts/research/render_research_docs.py [--check]
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "audit"))
import modern_data as M  # noqa: E402

ROOT = M.ROOT
OUT = ROOT / "docs" / "research"
NA = "NOT_ASSESSED"
HEADER = (
    "> Generated by `scripts/research/render_research_docs.py` from `docs/research/`. Do not edit by hand.\n"
    f"> Research cutoff (Stage A): **{M.CUTOFF}**. Stage B refresh targeted at **{M.REFRESH_TARGET}**: `PENDING_FUTURE_REFRESH` "
    "(not performed; no event after the cutoff is claimed).\n"
)
METHOD_MEANING = {
    "PRIMARY_DOCUMENT_READ": ("A primary document/page was downloaded and the cited passage read directly.", "Yes"),
    "EXECUTED": ("The claim was reproduced by running code in a clean environment (see section 4).", "Yes, for the stated version only"),
    "REGISTRY_API": ("Machine-readable package-registry or lifecycle data retrieved by `scripts/research/fetch_registry_versions.py`.", "Yes, for version/date statements"),
    "OFFICIAL_PAGE_SUMMARY": ("An official page was fetched through a summarising tool; the summary was NOT cross-checked against raw text.", "No: re-verify against the primary text first"),
    "SECONDARY_SOURCE": ("Trade press or other non-primary coverage; carries a caveat.", "No"),
}


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(M.md(c) for c in r) + " |")
    return "\n".join(out)


def short(text, n=220) -> str:
    t = " ".join(str(text).split())
    return t if len(t) <= n else t[: n - 3].rstrip() + "..."


def probe_tech(d: M.Data) -> dict[str, list[str]]:
    """probe id -> registry technology ids (via pinned package names and the executed runtime)."""
    by_pkg: dict[str, str] = {}
    for tid, e in d.registry.items():
        for f in e.get("fetch", []) or []:
            if f["kind"] in ("pypi", "npm") and f.get("name"):
                by_pkg[f["name"].lower().replace("_", "-")] = tid
    out: dict[str, list[str]] = {}
    for pid, p in d.probes.items():
        techs: set[str] = set()
        for pin in p.get("pins", []):
            name = pin.split("==")[0].split("@")[0].lower().replace("_", "-")
            if name in by_pkg:
                techs.add(by_pkg[name])
        runtime = p.get("runtime", "")
        if runtime == "python":
            techs.add("python")
        if runtime in ("node", "npm-view", "eslint", "tsc"):
            techs.add("node")
        out[pid] = sorted(techs)
    return out


def cycles_text(rec: dict, limit: int = 4) -> str:
    cyc = rec.get("supported_cycles") or []
    if not cyc:
        return NA
    return "; ".join(f"{c['cycle']} (latest {c['latest']}, EOL {c['eol']}{', LTS' if c.get('lts') else ''})" for c in cyc[:limit]) + (" ..." if len(cyc) > limit else "")


def version_text(d: M.Data, tid: str) -> str:
    recs = d.snapshot_all.get(tid, [])
    parts = []
    for r in recs:
        if r.get("current"):
            c = r["current"]
            parts.append(f"{c['version']} ({c['date']}; {r['kind']})")
    return "; ".join(parts) if parts else ""


def register_text(d: M.Data, tid: str) -> str:
    refs = [r for r in d.registry[tid].get("register", []) if r in d.register]
    return "; ".join(f"{r}: {short(d.register[r].get('version', d.register[r]['title']), 90)} ({d.register[r]['method']})" for r in refs)


def verified_text(d: M.Data, tid: str) -> str:
    v, r = version_text(d, tid), register_text(d, tid)
    return " | ".join(x for x in (v, r) if x)


def verified_on(d: M.Data, tid: str) -> str:
    dates = [rec["retrieved_utc"][:10] for rec in d.snapshot_all.get(tid, []) if rec.get("current")]
    dates += [d.register[r]["verified_on"] for r in d.registry[tid].get("register", []) if r in d.register]
    return max(dates) if dates else "n/a"


def docs_url(d: M.Data, tid: str) -> str:
    e = d.registry[tid]
    if e.get("official_docs"):
        return e["official_docs"]
    for r in e.get("register", []):
        if r in d.register and (d.register[r].get("primary_url") or d.register[r].get("url")):
            return d.register[r].get("primary_url") or d.register[r]["url"]
    return NA


def status_text(d: M.Data, tid: str) -> str:
    recs = d.snapshot_all.get(tid, [])
    if not recs:
        e = d.registry[tid]
        return "no version source configured" if not e.get("fetch") else "not fetched"
    return ", ".join(sorted({r.get("status", "OK") for r in recs if not r.get("current")})) or "OK"


def render_baselines(d: M.Data) -> str:
    use = M.tech_usage(d)
    ptech = probe_tech(d)
    rules_by_tech: dict[str, list[dict]] = defaultdict(list)
    for r in d.rules:
        for t in r.get("tech", []):
            rules_by_tech[t].append(r)
    probes_by_tech: dict[str, list[str]] = defaultdict(list)
    for pid, techs in ptech.items():
        for t in techs:
            probes_by_tech[t].append(pid)

    def courses_modules(tid: str) -> tuple[str, str]:
        u = use.get(tid)
        if not u:
            return "not detected in the legacy sources", ""
        courses = ", ".join(c.replace("COURSE-", "") for c, _ in u["courses"].most_common(4)) or "no mapped destination"
        mods = ", ".join(m for m, _ in u["modules"].most_common(5))
        return courses, mods

    tier1 = sorted(t for t in d.registry if rules_by_tech.get(t) or probes_by_tech.get(t))
    verified = sorted(t for t in d.registry if verified_text(d, t) and t not in tier1)
    detected_unverified = sorted(t for t in d.registry if t not in tier1 and t not in verified and t in use)
    never_detected = sorted(t for t in d.registry if t not in tier1 and t not in verified and t not in use)

    lines = [
        "# Technology Baselines (October 2026)", "", HEADER,
        "One row per technology in `docs/research/technology_registry.yaml` (" + f"{len(d.registry)} entries). A baseline states what is verified as current **on {M.CUTOFF}**, "
        "where the evidence came from, and what could not be assessed. **`NOT_ASSESSED` means no evidence was gathered; it never means \"fine\".** "
        "`UNVERIFIED_CURRENCY` means the technology is taught in the legacy sources but no version source could be queried.", "",
        "## 1. How to read this document", "",
        "- **Verified current** comes from the registry snapshot (`docs/research/data/registry_snapshot_2026-10-14.json`): PyPI, npm, Maven Central (`maven-metadata.xml` and POM upload time) and endoflife.date; "
        "and/or from the research-register entries linked in the registry (`register:` field), shown as `R-nnn: state (method)`. Dates are release/upload dates as the registry reports them, not announcement dates.",
        "- **Supported versions / lifecycle** is shown only where endoflife.date publishes cycles. Everything else is `NOT_ASSESSED`.",
        "- **Compatibility, Security, Migration, Test environment** are derived from the deprecation rules (`docs/research/deprecation_rules.yaml`) and the executed probes "
        "(`docs/research/data/api_probes_2026-10-14.json`) that concern the technology. A technology with no rule and no probe has none of these and is listed in the compact tables.",
        "- **GitHub release data was not collected.** The session's GitHub scope is restricted to this repository, so 31 registry entries whose only version source is a GitHub repository are `SKIPPED_GITHUB_NOT_ENABLED`.",
        "- Facts about standards, frameworks and vendor lifecycles (not package versions) are in section 7 with their register ids; the evidence method for each is in "
        "[RESEARCH_VERIFICATION_2026.md](RESEARCH_VERIFICATION_2026.md).", "",
        f"Coverage: **{len(tier1)}** technologies with rule/probe-backed baselines (section 2), **{len(verified)}** with a verified version only (section 3), "
        f"**{len(detected_unverified)}** taught but unverified (section 4), **{len(never_detected)}** registered for new content, not found in the sources (section 5).", "",
        "## 2. Technologies with rule- or probe-backed baselines", "",
    ]
    rows = []
    for tid in tier1:
        e = d.registry[tid]
        courses, mods = courses_modules(tid)
        rs = rules_by_tech.get(tid, [])
        compat = []
        rec = d.snapshot.get(tid)
        if rec:
            if rec.get("requires_python"):
                compat.append(f"requires Python {rec['requires_python']}")
            if rec.get("engines"):
                compat.append("engines " + ", ".join(f"{k} {v}" for k, v in rec["engines"].items()))
        compat += [short(r["current"], 160) for r in rs if r["issue"] in ("OBSOLETE_API", "END_OF_LIFE_VERSION", "OLD_BASELINE", "SUPERSEDED_STANDARD") and r["severity"] in ("P1", "P2")][:2]
        sec = [short(f"{r['label']}: {r['current']}", 200) for r in rs if r["issue"] in ("SECURITY_ANTIPATTERN", "INCORRECT_CLAIM", "LEGAL_ETHICS_REVIEW")]
        mig = [f"{r['label']} -> {short(r['replacement'], 120)}" for r in rs if r.get("replacement")][:3]
        test = []
        for pid in probes_by_tech.get(tid, []):
            p = d.probes[pid]
            test.append(f"`{pid}`: {p['status']}, {p.get('python', p.get('runtime', ''))}, pins {', '.join(p.get('pins', [])) or 'none'}")
        unresolved = []
        if not verified_text(d, tid):
            unresolved.append(f"version not verified ({status_text(d, tid)})")
        elif not version_text(d, tid):
            unresolved.append("no package version; state verified from the register only")
        if docs_url(d, tid) == NA:
            unresolved.append("no official-docs URL recorded")
        rec_c = d.snapshot.get(tid) or {}
        rows.append([
            f"**{tid}** ({e['domain']})", f"{courses}; {mods}".strip("; "),
            verified_text(d, tid) or "UNVERIFIED_CURRENCY",
            cycles_text(rec_c) if rec_c.get("kind") == "endoflife" else NA,
            docs_url(d, tid), verified_on(d, tid),
            "; ".join(compat) or NA, "; ".join(sec) or NA, "; ".join(mig) or NA, "; ".join(test) or "NOT_TESTED", "; ".join(unresolved) or "none recorded"])
    lines += [table(["Technology", "Courses; modules (from page records)", "Verified current (date; source)", "Supported versions / lifecycle", "Official docs", "Verified on", "Compatibility", "Security", "Migration from taught pattern", "Test environment", "Unresolved"], rows), ""]

    lines += ["## 3. Technologies with a verified version and no rule or probe", "",
              "Version/state is verified (package registry and/or a research-register entry); compatibility, security, migration and test environment are `NOT_ASSESSED` (no rule or executed probe concerns them yet).", ""]
    rows = []
    for tid in verified:
        rec = d.snapshot.get(tid, {})
        courses, mods = courses_modules(tid)
        rows.append([tid, d.registry[tid]["domain"], f"{courses}; {mods}".strip("; ") or NA, verified_text(d, tid),
                     cycles_text(rec, 3) if rec.get("kind") == "endoflife" else NA, docs_url(d, tid), verified_on(d, tid)])
    lines += [table(["Technology", "Domain", "Courses; modules", "Verified current (date; source)", "Supported versions / lifecycle", "Official docs", "Verified on"], rows), ""]

    lines += ["## 4. Taught in the legacy sources, currency unverified", "",
              "These technologies appear in the PDFs but no version source could be queried (no package registry entry, or GitHub-only). "
              "Every page mentioning them carries `currency_status: UNVERIFIED_CURRENCY` unless a deprecation rule fires. They need a primary-source check before any customer-facing version claim.", ""]
    rows = []
    for tid in detected_unverified:
        courses, mods = courses_modules(tid)
        rows.append([tid, d.registry[tid]["domain"], f"{use[tid]['pages']:,}", f"{courses}; {mods}".strip("; "), status_text(d, tid), docs_url(d, tid)])
    lines += [table(["Technology", "Domain", "Pages", "Courses; modules", "Why unverified", "Official docs"], rows), ""]

    lines += ["## 5. Registered for new content, not found in the legacy sources", "",
              "Technologies the modernized catalog may teach (see `docs/curriculum/`) that the PDFs never mention, or that the detection pattern did not match. Status is as in section 4.", ""]
    rows = []
    for tid in never_detected:
        rows.append([tid, d.registry[tid]["domain"], verified_text(d, tid) or "UNVERIFIED_CURRENCY", status_text(d, tid) if not verified_text(d, tid) else "OK"])
    lines += [table(["Technology", "Domain", "Verified current (date; source)", "Source status"], rows), ""]

    lines += ["## 6. Runtime and tool baselines used by the labs", "",
              "The labs run on the toolchain present in the build environment. The snapshot shows what is current; the lab evidence log (`docs/qa/LAB_EXECUTION_EVIDENCE.md`) records what was actually run.", ""]
    rows = []
    for tid in ("python", "node", "java", "jdk", "maven", "gradle", "junit", "selenium", "playwright", "pytest", "typescript", "react", "eslint", "kubernetes", "airflow"):
        if tid in d.snapshot:
            rec = d.snapshot[tid]
            rows.append([tid, version_text(d, tid), cycles_text(rec, 3) if rec.get("kind") == "endoflife" else NA])
    lines += [table(["Technology", "Verified current", "Supported cycles (endoflife.date)"], rows), ""]

    lines += ["## 7. Standards, frameworks and service lifecycles (register-backed)", "",
              "Facts that are not package versions. Each row is a research-register entry; `method` says how strongly it was verified.", ""]
    rows = []
    for rid, r in sorted(d.register.items()):
        rows.append([rid, short(r["title"], 120), short(r.get("version", ""), 110), r["publisher"], r["method"], r["verified_on"], r.get("primary_url") or r.get("url", ""),
                     ", ".join(a.replace("COURSE-", "") for a in r.get("applies_to", []))])
    lines += [table(["Register id", "Subject", "Version / state", "Publisher", "Method", "Verified on", "URL", "Applies to"], rows), ""]
    return "\n".join(lines)


def render_verification(d: M.Data) -> str:
    reg = list(d.register.values())
    meth = Counter(r["method"] for r in reg)
    probes = list(d.probes.values())
    snap_status = Counter(r.get("status", "OK") for rs in d.snapshot_all.values() for r in rs)
    kinds = Counter(r["kind"] for rs in d.snapshot_all.values() for r in rs)
    lines = ["# Research Verification (October 2026)", "", HEADER,
             "This is the ledger behind every currency claim in the modernization: what was checked, how, when, and what could **not** be verified. "
             "Nothing in the course content may state a fact about a version, date, standard or vendor lifecycle that is not traceable to a row here "
             "(`tests/test_repo_hygiene.py` and `scripts/audit/validate_modernization_data.py` enforce that references resolve).", "",
             "## 1. Scope, cutoff and the two-stage date policy", "",
             f"- **Stage A (done):** research cutoff and execution date **{M.CUTOFF}**. Package registries were queried with `--cutoff {M.CUTOFF}` so releases after the cutoff cannot become \"current\".",
             f"- **Stage B (`PENDING_FUTURE_REFRESH`):** the owner asked for a refresh through {M.REFRESH_TARGET}. It has **not** been performed. When it is, re-run `scripts/research/fetch_registry_versions.py --cutoff {M.REFRESH_TARGET}` "
             "and `scripts/research/api_probes.py --cutoff " + M.REFRESH_TARGET + "`, diff against the Stage A outputs, and update the register. Dates between the two stages are never back-filled.",
             "- Known dated events inside the window that the refresh must check are in `docs/release/OCT24_FINAL_REFRESH_CHECKLIST.md`.", "",
             "## 2. Evidence methods", "",
             table(["Method", "Entries", "What it proves", "Usable for customer-facing claims"],
                   [[m, meth.get(m, 0), METHOD_MEANING[m][0], METHOD_MEANING[m][1]] for m in METHOD_MEANING]), "",
             "Source preference order used throughout: (1) official specification, standard or vendor documentation; (2) the project's own release notes; (3) package-registry metadata; "
             "(4) executed behaviour; (5) secondary coverage, always flagged. Marketing pages, social posts and uncited blog claims were not used as evidence.", "",
             "## 3. Registry snapshot provenance", "",
             f"- File: `docs/research/data/registry_snapshot_{M.CUTOFF}.json`; produced by `scripts/research/fetch_registry_versions.py` (stdlib HTTP only, no credentials, no paid API).",
             f"- Records: **{sum(kinds.values())}** across {len(d.snapshot_all)} technologies; by source kind: {M.counts_str(kinds)}.",
             f"- Outcome: {M.counts_str(snap_status)}. `SKIPPED_GITHUB_NOT_ENABLED` means no GitHub query was attempted because the session is scoped to this repository; those technologies have no verified version.",
             "- Maven dates are the POM upload time (`Last-Modified`), not the project's announcement date; the record states this in `date_basis`.", ""]
    skipped = sorted(t for t, rs in d.snapshot_all.items() if all(r.get("status") != "OK" for r in rs))
    if skipped:
        lines += ["Technologies with no verified version from the snapshot: " + ", ".join(f"`{t}`" for t in skipped) + ".", ""]
    lines += ["## 4. Executed API probes", "",
              "Each probe installs pinned, snapshot-current versions into a throw-away virtual environment **outside the repository** and runs a few lines that exercise exactly the pattern the legacy PDFs teach. "
              f"The result is the observed behaviour on the stated version, on {d.probe_meta.get('host', 'the build host')}. A probe proves behaviour on that version only.", "",
              table(["Probe", "Taught pattern", "Status", "Runtime", "Pins", "Observed (abridged)", "Executed (UTC)"],
                    [[p["id"], p["taught_pattern"], p["status"], p.get("python", p.get("runtime", "")), ", ".join(p.get("pins", [])) or "-", short(json.dumps(p.get("observed", {}), sort_keys=True), 260), p["executed_utc"]] for p in probes]), "",
              "Re-run: `.venv/bin/python scripts/research/api_probes.py --work-dir <dir outside the repo> --cutoff 2026-10-14` (network required; not run in CI).", "",
              "## 5. Research register ledger", "",
              f"{len(reg)} entries in `docs/research/research_register.yaml`. `Used by` lists the findings, change records and rules that cite the entry.", ""]
    used: dict[str, set[str]] = defaultdict(set)
    for f in d.findings.values():
        for r in f.get("reference", []) or []:
            used[r].add(f["id"])
    for ch in d.changes:
        for r in ch["ref"]:
            used[str(r)].add(ch["id"])
    for nd in d.devs:
        for r in nd["research"]:
            used[str(r)].add(nd["id"])
    for rule in d.rules:
        for r in rule.get("evidence", []):
            used[str(r)].add(rule["id"])
    rows = []
    for rid, r in sorted(d.register.items()):
        rows.append([rid, short(r["title"], 130), r["publisher"], short(r.get("version", ""), 90), r["method"], r["verified_on"], r.get("primary_url") or r.get("url", ""),
                     "yes" if r.get("caveat") else "", short(", ".join(sorted(used.get(rid, []))) or "-", 120)])
    lines += [table(["Id", "Subject", "Publisher", "Version / state", "Method", "Verified on", "URL", "Caveat", "Used by"], rows), "",
              "## 6. Limitations and items that must not be used in customer-facing material yet", ""]
    weak = [r for r in reg if r["method"] in ("OFFICIAL_PAGE_SUMMARY", "SECONDARY_SOURCE")]
    lines += [f"{len(weak)} register entries rest on a summarised official page or a secondary source. Re-verify each against the primary text before publication:", "",
              table(["Id", "Subject", "Method", "Caveat / what to re-check"], [[r["id"], short(r["title"], 110), r["method"], short(r.get("caveat", "re-verify against the primary page text"), 220)] for r in weak]), ""]
    open_nd = [nd for nd in d.devs if nd["maturity"] in ("EXPERIMENTAL", "SPECULATIVE") or "NOT_ASSESSED" in nd["adoption_evidence"] or "not assessed" in nd["adoption_evidence"].lower() or "not read" in nd["adoption_evidence"].lower()]
    lines += ["New developments whose adoption evidence is incomplete (see [NEW_DEVELOPMENTS_2026.md](NEW_DEVELOPMENTS_2026.md)): " + ", ".join(nd["id"] for nd in open_nd) + ".", "",
              "Not researched in this pass (no claim is made about them): vendor pricing pages, GitHub release feeds (not enabled), regulatory texts beyond the register entries, "
              "and any change published after the cutoff.", ""]
    return "\n".join(lines)


def render_developments(d: M.Data) -> str:
    devs = d.devs
    mat = Counter(nd["maturity"] for nd in devs)
    lines = ["# New Developments Since the 2025 Sources (October 2026)", "", HEADER,
             "Developments that emerged or changed after the legacy PDFs were written, classified by maturity, with the evidence actually gathered. "
             "Curated in `docs/research/new_developments.yaml`; every research reference resolves in the register.", "",
             "## Classification", "",
             table(["Maturity", "Meaning", "Teaching rule"], [
                 ["STABLE", "Generally available or a final standard, widely supported.", "May be taught as current practice with a version statement."],
                 ["EMERGING", "Usable and documented but young, preview, or with limited adoption evidence.", "Teach with an explicit maturity note and a stable fallback."],
                 ["EXPERIMENTAL", "Research or preview features.", "Optional enrichment only; never replaces stable fundamentals."],
                 ["SPECULATIVE", "Announced direction only.", "Mention as a watch item; no labs."]]), "",
             "`adoption_evidence` records what was actually seen; \"not assessed\" means no adoption data was gathered, **not** that adoption is low. "
             "`commercial` entries are hypotheses for the product team, never demand claims.", "",
             f"{len(devs)} developments: {M.counts_str(mat, ['STABLE', 'EMERGING', 'EXPERIMENTAL', 'SPECULATIVE'])}.", "",
             "## Summary", "",
             table(["ID", "Development", "Domain", "Date", "Maturity", "Action", "Modules", "Evidence methods"],
                   [[nd["id"], nd["title"], nd["domain"], nd["date"], nd["maturity"], nd["action"], ", ".join(nd["modules"]),
                     ", ".join(sorted({d.register[r]["method"] for r in nd["research"] if str(r).startswith("R-") and r in d.register})) or "-"] for nd in devs]), ""]
    by_domain: dict[str, list[dict]] = defaultdict(list)
    for nd in devs:
        by_domain[nd["domain"]].append(nd)
    for dom, items in sorted(by_domain.items()):
        lines += [f"## {dom}", ""]
        for nd in items:
            lines += [f"### {nd['id']} - {nd['title']}", "",
                      f"- **Date:** {nd['date']}  |  **Maturity:** {nd['maturity']}  |  **Action:** {nd['action']}  |  **Courses:** {', '.join(nd['courses'])}  |  **Modules:** {', '.join(nd['modules'])}",
                      f"- **Adoption evidence:** {nd['adoption_evidence']}",
                      f"- **Relevance:** {nd['relevance']}",
                      f"- **Security:** {nd['security']}",
                      f"- **Operations:** {nd['operations']}",
                      f"- **Commercial usefulness (hypothesis):** {nd['commercial']}",
                      f"- **Prerequisites:** {nd['prerequisites']}",
                      "- **Evidence:**"]
            for ref in nd["research"]:
                r = d.resolve(str(ref))
                lines.append(f"  - `{r['label']}`: {r['detail']}" + (f" <{r['url']}>" if r["url"] else ""))
            lines.append("")
    return "\n".join(lines)


def render_all(d: M.Data) -> dict[Path, str]:
    out = {
        OUT / "TECHNOLOGY_BASELINES_2026.md": render_baselines(d),
        OUT / "RESEARCH_VERIFICATION_2026.md": render_verification(d),
        OUT / "NEW_DEVELOPMENTS_2026.md": render_developments(d),
    }
    return {p: t.rstrip() + "\n" for p, t in out.items()}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = M.Data()
    bad = []
    for path, text in render_all(d).items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                bad.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)} ({len(text):,} bytes)")
    if bad:
        print("DRIFT:", *bad, sep="\n  ")
        return 1
    return 0


