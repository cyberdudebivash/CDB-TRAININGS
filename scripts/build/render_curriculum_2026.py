EVIDENCE_BY_LEVEL = {
    0: "Guided-lab automated checks plus a retrieval quiz",
    1: "Guided-lab automated checks plus a short rubric-scored artefact",
    2: "Independent lab graded by automated criteria and a reviewer rubric",
    3: "Capstone or multi-source case with a written decision record, graded against a published rubric",
}


def md(text) -> str:
    return M.md(text)


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(md(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def hours(h: float) -> str:
    return str(int(h)) if float(h).is_integer() else f"{h:g}"


def change_index(d: M.Data) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    mc: dict[str, list[str]] = defaultdict(list)
    nd: dict[str, list[str]] = defaultdict(list)
    for ch in d.changes:
        for m in ch["implemented"]["modules"]:
            mc[m].append(ch["id"])
    for dev in d.devs:
        for m in dev["modules"]:
            nd[m].append(dev["id"])
    return mc, nd


def render_pathways(d: M.Data) -> str:
    pw = M.load_yaml("catalog/learning-pathways.yaml")
    mc, nd = change_index(d)
    module_info = {m["id"]: m for c in d.catalog["courses"] for m in c["modules"]}
    lines = ["# Master Skill Pathways (October 2026)", "", HEADER,
             "Role-oriented learning pathways assembled from the module catalog. Levels describe **learning evidence inside this academy** (what a learner can demonstrate), "
             "not job titles, salary bands or equivalence to any external certification. Hours are planning estimates (authoring budgets), not measured learner times. "
             "No module except the SOC-M04 pilot is built yet, so every other module below is `PLANNED`.", "",
             "## Competency levels", "",
             table(["Level", "Name", "Descriptor", "Evidence of attainment", "Supervision"],
                   [[lv["id"], lv["name"], lv["descriptor"], lv["evidence"], lv["supervision"]] for lv in pw["levels"]]), "",
             "## Pathway overview", ""]
    rows = []
    path_modules: dict[str, list[dict]] = {}
    for p in pw["pathways"]:
        mods: list[dict] = []
        seen: set[str] = set()
        for step in p["steps"]:
            for m in pathway_modules(step, d.courses[step["course"]]):
                if m["id"] not in seen:
                    seen.add(m["id"])
                    mods.append(m)
        path_modules[p["id"]] = mods
        built = sum(1 for m in mods if m["status"] != "PLANNED")
        new2026 = sorted({x for m in mods for x in nd.get(m["id"], [])})
        rows.append([p["id"], p["title"], p["audience"], len(mods), hours(sum(m["estimated_hours"] for m in mods)), built, p["capstone_module"], len(new2026)])
    lines += [table(["Pathway", "Title", "Audience", "Modules", "Planned hours", "Built", "Capstone", "2026 developments"], rows), "",
              "`2026 developments` counts the distinct `ND-*` entries in [NEW_DEVELOPMENTS_2026.md](../research/NEW_DEVELOPMENTS_2026.md) whose destination modules lie on the pathway.", ""]
    for p in pw["pathways"]:
        mods = path_modules[p["id"]]
        lines += [f"## {p['id']} - {p['title']}", "", f"**Audience:** {p['audience']}  ", f"**Sequence:** " + " -> ".join(
            f"{s['course'].replace('COURSE-', '')}" + (f" ({len(s['modules'])} modules)" if s.get("modules") else "") for s in p["steps"]) + f"  ", f"**Capstone:** `{p['capstone_module']}` - {md(module_info[p['capstone_module']]['title'])}", ""]
        for s in p["steps"]:
            if s.get("note"):
                lines.append(f"- Step note ({s['course']}): {s['note']}")
        lines += ["", table(["#", "Module", "Title", "Level", "Hours", "State", "Change records", "Developments"],
                            [[i, m["id"], m["title"], m["level"], hours(m["estimated_hours"]), m["status"], ", ".join(sorted(mc.get(m["id"], []))) or "-",
                              ", ".join(sorted(nd.get(m["id"], []))) or "-"] for i, m in enumerate(mods, 1)]), ""]
    domains: dict[str, list[str]] = defaultdict(list)
    for c in d.catalog["courses"]:
        domains[DOMAIN.get(c["id"], "Other")].append(f"{c['id']} ({len(c['modules'])} modules)")
    lines += ["## Skill domains", "", table(["Domain", "Courses"], [[k, "; ".join(v)] for k, v in sorted(domains.items())]), "",
              "## What the 2026 research added to the pathways", "",
              "Modules created because the legacy sources lacked them or because a verified 2026 development requires them (they have no source pages; see "
              "[COURSE_SOURCE_TRACEABILITY.md](../audits/COURSE_SOURCE_TRACEABILITY.md)):", ""]
    new_mods = []
    for c in d.catalog["courses"]:
        for m in c["modules"]:
            if nd.get(m["id"]) and any(dev["action"] in ("ADD", "EXPAND") for dev in d.devs if dev["id"] in nd[m["id"]]):
                new_mods.append([m["id"], m["title"], c["id"], ", ".join(sorted(nd[m["id"]]))])
    lines += [table(["Module", "Title", "Course", "Developments"], new_mods), ""]
    return "\n".join(lines)


def bloom(outcome: str) -> str:
    verb = outcome.split()[0].lower().strip(",.")
    return VERB_BLOOM.get(verb, "Unclassified")


def render_outcomes(d: M.Data) -> str:
    mc, nd = change_index(d)
    lines = ["# Competency Outcomes (October 2026)", "", HEADER,
             "Every module has one primary, observable outcome. This document lists them with the evidence that will demonstrate each (from "
             "[ASSESSMENT_FRAMEWORK.md](../standards/ASSESSMENT_FRAMEWORK.md)) and the research that drives it. **Status is honest:** an outcome counts as assessed only when "
             "`assessment_coverage` in the catalog says so (currently the SOC-M04 pilot). The planned evidence column is a plan, not a result; item quality has not been validated by a learner pilot "
             "or subject-matter review.", "",
             "Bloom classification is derived from the outcome's leading verb by a fixed table in the generator (`Unclassified` when the verb is not in the table); it is a convenience label, not a validated taxonomy judgement.", ""]
    total = Counter()
    for c in d.catalog["courses"]:
        cov = c["assessment_coverage"]
        lines += [f"## {c['id']} - {c['title']}", "",
                  f"Outcomes total: **{cov['outcomes_total']}**; assessed: **{cov['outcomes_assessed']}**; labs planned/built/verified: "
                  f"{c['lab_coverage']['planned']}/{c['lab_coverage']['built']}/{c['lab_coverage']['verified_executable']}; release status `{c['release_status']}`.", ""]
        rows = []
        for m in c["modules"]:
            b = bloom(m["primary_outcome"])
            total[b] += 1
            rows.append([m["id"], m["level"], m["primary_outcome"], b, EVIDENCE_BY_LEVEL.get(m["level"], "-"), m.get("lab_state", "PLANNED" if m["status"] == "PLANNED" else m["status"]),
                         ", ".join(sorted(mc.get(m["id"], []))) or "-", ", ".join(sorted(nd.get(m["id"], []))) or "-"])
        lines += [table(["Module", "Level", "Outcome (observable)", "Bloom", "Planned evidence", "Lab / build state", "Change records", "Developments"], rows), ""]
    lines += ["## Distribution of cognitive levels", "", table(["Bloom level", "Modules"], [[k, v] for k, v in sorted(total.items(), key=lambda kv: (-kv[1], kv[0]))]), "",
              "A portfolio that is mostly `Apply` and `Analyse` with `Create` at capstones matches the framework's intent that performance, not recall, is assessed. "
              "Outcome counts in the catalog (`outcomes_total`) include capstone sub-outcomes that are not separate rows here.", ""]
    return "\n".join(lines)


def render_all(d: M.Data) -> dict[Path, str]:
    return {OUT / "MASTER_SKILL_PATHWAYS_2026.md": render_pathways(d).rstrip() + "\n", OUT / "COMPETENCY_OUTCOMES_2026.md": render_outcomes(d).rstrip() + "\n"}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = M.Data()
    bad = []
    for path, text in render_all(d).items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                bad.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)} ({len(text):,} bytes)")
    if bad:
        print("DRIFT:", *bad, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
