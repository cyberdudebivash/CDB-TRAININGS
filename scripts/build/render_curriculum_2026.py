#!/usr/bin/env python3
"""Render docs/curriculum/MASTER_SKILL_PATHWAYS_2026.md and docs/curriculum/COMPETENCY_OUTCOMES_2026.md.

Inputs : catalog/courses.yaml, catalog/learning-pathways.yaml, docs/audits/data/modernization_changes.yaml,
         docs/research/new_developments.yaml (via scripts/audit/modern_data.py)
Output : deterministic Markdown, no timestamps.

Run:    .venv/bin/python scripts/build/render_curriculum_2026.py [--check]
"""
from __future__ import annotations

