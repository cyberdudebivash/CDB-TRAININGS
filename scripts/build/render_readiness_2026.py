def render_all(d: M.Data) -> dict[Path, str]:
    r = Report(d)
    out = {ROOT / "docs/release/OCT2026_PRODUCTION_READINESS.md": r.readiness(), ROOT / "docs/commercial/PREMIUM_COURSE_CATALOG_2026.md": r.premium_catalog(),
           ROOT / "docs/release/OCT24_FINAL_REFRESH_CHECKLIST.md": r.checklist(), ROOT / "docs/qa/ALL_COURSES_QA_REPORT.md": r.qa_report(),
           ROOT / "docs/ops/MODERNIZATION_PROGRESS.md": r.progress()}
    return {p: t.rstrip() + "\n" for p, t in out.items()}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    d = M.Data()
    bad = []
    for path, text in render_all(d).items():
        if a.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                bad.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)} ({len(text):,} bytes)")
    if bad:
        print("DRIFT:", *bad, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
