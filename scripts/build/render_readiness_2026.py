    # ------------------------------------------------------------------ metrics
    def course_metrics(self, c: dict) -> dict:
        d = self.d
        mods = c["modules"]
        built = [m for m in mods if m["status"] != "PLANNED"]
        labs, outs = c["lab_coverage"], c["assessment_coverage"]
        chs = [ch for ch in d.changes if ch["course"] == c["id"]]
        verified = [ch for ch in chs if ch["verification"]["status"] in ("EXECUTED", "RESEARCH_VERIFIED")]
        opened = [ch for ch in chs if ch["verification"]["status"] in OPEN_VERIFICATION]
        recs = [r for s in (c.get("source_ids") or []) for r in d.records[s]]
        pages = len(recs)
        sev = Counter(r["severity"] for r in recs)
        status = Counter(r["verification_status"] for r in recs)
        cur = Counter(r["currency_status"] for r in recs)
        fields: dict[str, dict] = {}
        frac_research = len(verified) / len(chs) if chs else 0.0
        fields["research_currency"] = {"status": "NOT_ASSESSED" if not chs else "PARTIAL" if verified else "NOT_MET", "fraction": frac_research,
                                       "detail": "no legacy source, so no change records" if not chs else f"{len(verified)} of {len(chs)} change records EXECUTED or RESEARCH_VERIFIED; {len(opened)} open; Stage B pending"}
        built_exec = [m for m in built if m.get("lab_state") == "VERIFIED_EXECUTABLE"]
        frac_tech = len(built_exec) / len(mods)
        fields["technical_correctness"] = {"status": "PARTIAL" if built_exec else "NOT_ASSESSED", "fraction": frac_tech,
                                           "detail": f"{len(built_exec)} of {len(mods)} modules built with executed labs; no SME review" if built_exec else "nothing built to assess"}
        frac_cur = len(built) / len(mods)
        fields["curriculum_completeness"] = {"status": "MET" if len(built) == len(mods) else "PARTIAL" if built else "NOT_MET", "fraction": frac_cur, "detail": f"{len(built)} of {len(mods)} modules built"}
        frac_lab = labs["verified_executable"] / labs["planned"]
        fields["lab_readiness"] = {"status": "MET" if labs["verified_executable"] == labs["planned"] else "PARTIAL" if labs["verified_executable"] else "NOT_MET", "fraction": frac_lab,
                                   "detail": f"{labs['verified_executable']} of {labs['planned']} labs verified executable ({labs['built']} built)"}
        frac_as = outs["outcomes_assessed"] / outs["outcomes_total"]
        fields["assessment_readiness"] = {"status": "MET" if outs["outcomes_assessed"] == outs["outcomes_total"] else "PARTIAL" if outs["outcomes_assessed"] else "NOT_MET", "fraction": frac_as,
                                          "detail": f"{outs['outcomes_assessed']} of {outs['outcomes_total']} outcomes assessed; no SME review, no learner pilot"}
        for key in ("editorial", "ip_licensing", "commercial", "academy_integration", "human_approval"):
            entry = (self.inputs["course_overrides"].get(c["id"], {}) or {}).get(key) or self.inputs["defaults"][key]
            blockers = entry.get("blockers", [])
            fields[key] = {"status": entry["status"], "fraction": 1.0 if entry["status"] == "MET" else 0.5 if entry["status"] == "PARTIAL" else 0.0,
                           "detail": entry["note"] + (f" Blockers: {', '.join(blockers)}." if blockers else "")}
        gate_a = {k: f for k, f in fields.items() if k in GATE_A_FIELDS}
        index = 100 * sum(1.0 if f["status"] == "MET" else f["fraction"] if f["status"] == "PARTIAL" else 0.0 for f in gate_a.values()) / len(gate_a)
        unmet = [k for k, f in gate_a.items() if f["status"] != "MET"]
        return {"mods": mods, "built": built, "labs": labs, "outs": outs, "changes": chs, "verified": verified, "open": opened, "pages": pages, "sev": sev, "status": status, "cur": cur,
                "fields": fields, "index": index, "unmet": unmet, "go": not unmet}

