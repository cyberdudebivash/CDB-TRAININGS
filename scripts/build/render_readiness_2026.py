def md(x) -> str:
    return M.md(x)


def table(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    return "\n".join(out + ["| " + " | ".join(md(c) for c in r) + " |" for r in rows])


def pct(x: float) -> str:
    return f"{100 * x:.0f} %"


class Report:
    def __init__(self, d: M.Data) -> None:
        self.d = d
        self.inputs = M.load_yaml("docs/release/data/readiness_inputs_2026.yaml")
