    def premium_catalog(self) -> str:
        d = self.d
        use = M.tech_usage(d)
        L = ["# Premium Course Catalog (October 2026) - status of each planned edition", "", HEADER,
             "This catalog lists the **planned** premium editions. **No edition may be titled \"Premium Edition\" or sold today**: the reserved title",
             "`CYBERDUDEBIVASH — <Course> — October 2026 Premium Edition` becomes usable only for a course that has reached `TRAINING_CONTENT_GO` (Gate A) "
             "([OCT2026_PRODUCTION_READINESS.md](../release/OCT2026_PRODUCTION_READINESS.md)); until then any build must be labelled as a preview or student pilot. "
             "No price is set (see [PRICING_AND_POSITIONING_RESEARCH.md](PRICING_AND_POSITIONING_RESEARCH.md), hypotheses only), and no listing exists.", "",
             "Every edition, when it exists, must disclose these items on its front matter: content revision date, research verification date, technical baseline, unverified external changes and next review date. "
             "The values below are what the disclosure would say **today**.", ""]
        for c in d.catalog["courses"]:
            m = self.metrics[c["id"]]
            sources = c.get("source_ids") or []
            techs: Counter = Counter()
            for t, u in use.items():
                n = sum(u["sources"].get(s, 0) for s in sources)
                if n and t in d.snapshot and d.snapshot[t].get("current"):
                    techs[t] = n
            baseline = "; ".join(f"{t} {d.snapshot[t]['current']['version']} ({d.snapshot[t]['current']['date']})" for t, _ in techs.most_common(8)) or "no verified baseline (net-new course; fixed when its modules are built)"
            open_ids = [ch["id"] for ch in m["open"]]
            L += [f"## {c['title']}", "",
                  f"- Course id `{c['id']}`, catalog version `{c['version']}`, audience: {'; '.join(c['audience'])}.",
                  f"- Reserved edition title (**not usable**): `CYBERDUDEBIVASH — {c['title']} — October 2026 Premium Edition`",
                  f"- Planned duration {c['estimated_duration_hours']} hours across {len(c['modules'])} modules (planning estimate, not measured learner time); capstone: {c['capstone']}",
                  f"- State today: {len(m['built'])} of {len(c['modules'])} modules built; labs verified {c['lab_coverage']['verified_executable']} of {c['lab_coverage']['planned']}; release status `{c['release_status']}`; evidence index {m['index']:.1f} / 100.",
                  f"- Unmet readiness fields: {', '.join(label for k, label in FIELDS if k in m['unmet'])}.", "",
                  "Edition disclosure (values today):", "",
                  table(["Item", "Value"], [
                      ["Content revision date", f"{c['last_verified']} (latest catalog verification; built modules carry their own `last_verified`)"],
                      ["Research verification date", f"Stage A {M.CUTOFF}; Stage B {M.REFRESH_TARGET} `PENDING_FUTURE_REFRESH`"],
                      ["Technical baseline", baseline],
                      ["Unverified external changes", (", ".join(open_ids) + " (see the course change log)") if open_ids else "none recorded"],
                      ["Next review date (proposed)", f"{M.REFRESH_TARGET} (Stage B), then at least every 90 days"]]), "",
                  table(["Module", "Title", "Level", "Hours", "State"], [[x["id"], x["title"], x["level"], x["estimated_hours"], x["status"] if x["status"] != "PLANNED" else "PLANNED"] for x in c["modules"]]), ""]
        return "\n".join(L)

