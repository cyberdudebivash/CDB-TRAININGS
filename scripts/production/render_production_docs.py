        rows = []
        for s in self.p.scenarios["scenarios"]:
            if s["classification"] in ("CONTROLLED_LIVE", "REPLAY_SIMULATION", "EXTERNAL_LIVE"):
                rows.append([s["id"], short(s["course"]), s["title"], s["classification"], self.p.scenario_state(s), s.get("note", "")])
