            "## 6. Technical currency", "",
            f"The research registry and executed API probes carry the cutoff **{self.p.summary['as_of']}**; the lab matrix recorded commit `{self.matrix_commit}`. This document was generated for execution date **{self.as_of}**. "
            f"The Stage B refresh is dated **{G.STAGE_B_DATE}** and cannot be executed or certified before that date (DEF-010). See TECHNICAL_CURRENCY_VALIDATION.md.", "",
